import { contrastRatio, hslToHex, hslToRgb } from './colour'
import { COLOUR_TOKENS, CONTRAST_PAIRS, DIVISIONS, type Theme } from './tokens'

function hex(name: string, theme: Theme): string {
  const token = COLOUR_TOKENS.find((t) => t.name === name)
  if (!token) throw new Error(`Unknown token ${name}`)
  return hslToHex(token[theme])
}

function ratio(foreground: string, background: string, theme: Theme): string {
  const fg = COLOUR_TOKENS.find((t) => t.name === foreground)
  const bg = COLOUR_TOKENS.find((t) => t.name === background)
  if (!fg || !bg) throw new Error(`Unknown token in pair ${foreground}/${background}`)
  return contrastRatio(hslToRgb(fg[theme]), hslToRgb(bg[theme])).toFixed(2)
}

/** Renders docs/design-system.md from the typed tokens (npm run docs:design). */
export function renderDesignDoc(): string {
  const lines: string[] = []
  const push = (...l: string[]) => lines.push(...l)

  push(
    '# Design system',
    '',
    '> Generated by `npm run docs:design` from `src/lib/design/tokens.ts`. Do not edit by hand;',
    '> a unit test fails when this file is out of date.',
    '',
    'The visual language of Kit de Atividades follows the AEP *Manual de Normas Gráficas, Marca Associativa*',
    '(Brand Book) and stays close to the rebranded public site (`escoteiros.pt/staging`, theme `escoteiros-2026`).',
    'Where they differ the choice is recorded in `docs/brand-handoff.md`.',
    '',
    '## Principles',
    '',
    '- Colours, type, radius and shadows come from tokens in `src/app/globals.css`. Components never hard-code hex, `rgb()` or Tailwind palette colours (a test enforces it).',
    '- Azul AEP is the action colour (buttons, links, titles). Verde-água AEP is the accent (focus, rules, motifs). Text on a teal fill is near-black.',
    '- Arial in Regular (400) and Bold (700) only (Brand Book p. 40). Garet is print-only.',
    '- 4 px corners on controls, cards, chips and callouts. Hairline borders at rest; elevation only on hover and floating layers.',
    '- Contrast meets WCAG 2.1 AA, measured below. Information never relies on colour alone.',
    '',
    '## Colour tokens',
    '',
    '| Token | Name | Role | Light | Dark |',
    '| --- | --- | --- | --- | --- |'
  )
  for (const t of COLOUR_TOKENS.filter((c) => !c.name.startsWith('division-'))) {
    push(`| \`--${t.name}\` | ${t.label} | ${t.role} | \`${hex(t.name, 'light')}\` | \`${hex(t.name, 'dark')}\` |`)
  }

  push(
    '',
    'Hex values are derived from the HSL triplets in `globals.css`, so they can differ from the Brand Book by one step of rounding.',
    'The Brand Book cream accent has no printed value and is intentionally not a token.',
    '',
    '## Division colours',
    '',
    'From the *Regulamento do Programa para Jovens* v1.2 (Dec 2024), by Pantone reference. Hex values are sRGB conversions',
    'awaiting confirmation by the brand owners. Division colours identify divisions only: never status, buttons, links or chrome.',
    'Use the `DivisionPill` component; it is the only place these tokens may appear.',
    '',
    '| Age group | Division | Ages | Pantone | Fill | Label | Contrast |',
    '| --- | --- | --- | --- | --- | --- | --- |'
  )
  for (const d of DIVISIONS) {
    const base = `division-${d.key}`
    push(
      `| \`${d.ageGroup}\` | ${d.name} | ${d.ages} | ${d.pantone} | \`${hex(base, 'light')}\` | \`${hex(`${base}-foreground`, 'light')}\` | ${ratio(`${base}-foreground`, base, 'light')} |`
    )
  }

  push(
    '',
    'White text on the Clã red is only 4.02:1, so its label is near-black. The Chefia pill is white and carries a 1 px border;',
    'in the dark theme every pill also gets a light outline (`--division-outline`).',
    '',
    '## Contrast contract',
    '',
    'Every pair below is measured by `tests/unit/design/tokens.test.ts`. "Never" pairs must stay below AA for small text.',
    '',
    '| Pair | Theme | Ratio | Rule |',
    '| --- | --- | --- | --- |'
  )
  for (const pair of CONTRAST_PAIRS) {
    for (const theme of pair.themes) {
      const rule =
        pair.expectation === 'pass' ? `at least ${pair.threshold}:1` : `must stay below ${pair.threshold}:1${pair.note ? ` (${pair.note})` : ''}`
      push(`| ${pair.name} | ${theme} | ${ratio(pair.foreground, pair.background, theme)} | ${rule} |`)
    }
  }

  push(
    '',
    'The Brand Book (pp. 29–30) calls white on `#00A5A5` AAA; it measures 3.03:1, so it is large text and non-text only.',
    '',
    '## Components and patterns',
    '',
    '| Pattern | Rule | Brand Book / source |',
    '| --- | --- | --- |',
    '| Primary button | Azul AEP, white Bold label, Azul escuro on hover, 4 px radius | pp. 60–62, public site |',
    '| Accent button | Verde-água AEP with near-black label (`variant="accent"`) | pp. 29–30 |',
    '| Secondary / outline | Azul muito claro surface, or Azul AEP outline | public site |',
    '| Text link | Azul AEP; `.link-emphasis` adds a 2 px teal underline; teal is never a small-text link colour | pp. 29–30 |',
    '| Card | White, hairline border, 3 px teal top rule, `.card-lift` hover (3 px, shadow) | public site |',
    '| Eyebrow | `Eyebrow` — 0.7 rem Bold uppercase, teal leaf | public site |',
    '| Callout | `Callout` — Azul AEP, white text, 6 px teal left border | public site |',
    '| Values strip | `ValuesStrip` — teal band, large (≥ 18.66 px) bold white text only | public site |',
    '| Header | White, hairline, Bold nav with 3 px teal underline for hover and current page | pp. 60–62 |',
    '| Footer | Azul escuro, white text | public site |',
    '| Focus | 3 px Verde-água outline, 2 px offset; white inside `.on-blue` | WCAG 2.4.7 |',
    '| Motifs | `Ring`, `Rhombus`, `Star` — decorative, `aria-hidden`; at most one gradient panel per page | p. 41, pp. 57–58 |',
    '| Gradients | `bg-gradient-brand`, `bg-gradient-brand-vertical`; palette colours only; text on them is large white | p. 41 |',
    '| Motion | 150–200 ms colour, border, shadow and card lift; none under `prefers-reduced-motion` | — |',
    '| Radius | 4 px (`rounded-lg`/`md`/`sm` all resolve to it); `rounded-panel` (24 px) for heroes only | public site |',
    '| Fact icons | `Fact`/`FactIcon` — Clock duration, Users group size, Target effort, MapPin location; same icon everywhere the fact appears (detail, card, table, filters, chips, programs) | — |',
    '| Division toggle | `DivisionToggle` — 44 px pill, `aria-pressed`; selected = division fill + check + ring, unselected = outline with bordered swatch | — |',
    '| Card divisions | One `DivisionPill` per division, fixed order, compact label (`ageGroupShort`), full wording and ages as accessible name | — |',
    '',
    '## Adding a component',
    '',
    '1. Pick colours from the token table by role; never type a colour.',
    '2. Use only `font-bold` and the default weight.',
    '3. Check any new text/background combination against the contrast contract; add the pair to `src/lib/design/tokens.ts` if it is new.',
    '4. Run `npm run docs:design` and `npm run test:run -- tests/unit/design`.',
    ''
  )

  return lines.join('\n')
}
